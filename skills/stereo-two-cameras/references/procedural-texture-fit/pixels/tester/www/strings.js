let lang = 'en';
export function setLanguage(l) { if (STRINGS[l]) lang = l; }
export function t(key, ...args) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  return s.replace(/\{(\d+)\}/g, (_, i) => String(args[+i]));
}
